// Testnet measurement campaign for BookingEscrow.
// Works on real Sepolia (--network sepolia) and on a local dry run (--network hardhat, Sepolia-like
// config: chainId 11155111, one block every 12 s). Writes results/<label>_tx.csv and results/<label>_summary.json.
//
// Env: N_BOOKINGS (default 50), CANCEL_SHARE (0.15), MODE (0 push | 1 accrue), LABEL, ESCROW, TOKEN (reuse deployments)
const hre = require("hardhat");
const fs = require("fs");
const { ethers } = hre;

const N = Number(process.env.N_BOOKINGS || 50);
const CANCEL_SHARE = Number(process.env.CANCEL_SHARE || 0.15);
const MODE = Number(process.env.MODE || 0);
const LABEL = process.env.LABEL || hre.network.name;
const sleep = ms => new Promise(r => setTimeout(r, ms));
function rng(seed) { let s = seed >>> 0; return () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 2 ** 32; }; }
const R = rng(20261022);

const rows = [];
async function send(fnName, signer, txPromiseFactory, bookingId) {
  const tSub = Date.now();
  let tx, rc, err = "";
  try { tx = await txPromiseFactory(); rc = await tx.wait(); }
  catch (e) { err = (e.shortMessage || e.message || "").slice(0, 120); }
  const tIncl = Date.now();
  const blk = rc ? await ethers.provider.getBlock(rc.blockNumber) : null;
  const row = { function: fnName, bookingId, from: signer.address, txHash: tx ? tx.hash : "", status: rc ? rc.status : 0,
    block: rc ? rc.blockNumber : "", blockTimestamp: blk ? blk.timestamp : "", submitMs: tSub, inclusionMs: tIncl,
    inclusionLatencyS: ((tIncl - tSub) / 1000).toFixed(2),
    blockLatencyS: blk ? (blk.timestamp - tSub / 1000).toFixed(2) : "", gasUsed: rc ? rc.gasUsed.toString() : "",
    effectiveGasPriceGwei: rc ? ethers.formatUnits(rc.gasPrice ?? rc.effectiveGasPrice ?? 0n, "gwei") : "", error: err };
  rows.push(row);
  return { rc, row };
}

async function finalityLatency(sample) {
  // time until the block of each sampled tx is <= the 'finalized' block (Sepolia: ~13–20 min)
  const out = [];
  const deadline = Date.now() + Number(process.env.FINALITY_TIMEOUT_MS || 25 * 60 * 1000);
  const pending = new Set(sample.map(r => r.txHash));
  while (pending.size && Date.now() < deadline) {
    let fin; try { fin = await ethers.provider.getBlock("finalized"); } catch { break; }
    if (!fin) break;
    for (const r of sample) if (pending.has(r.txHash) && Number(r.block) <= fin.number) { out.push((Date.now() - r.submitMs) / 1000); pending.delete(r.txHash); }
    await sleep(12_000);
  }
  return out;
}

const q = (a, p) => { if (!a.length) return null; const s = [...a].sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(p * (s.length - 1) + 0.5))]; };

async function main() {
  const signers = await ethers.getSigners();
  const net = await ethers.provider.getNetwork();
  let admin, platform, affiliate, sdg, hotel, guests, ephemeral = false;
  if (signers.length >= 6 && process.env.EPHEMERAL !== "1") {
    [admin, platform, affiliate, sdg, hotel] = signers; guests = signers.slice(5);
  } else {
    // ONE funded key is enough: role addresses and guest wallets are generated and funded automatically
    ephemeral = true;
    admin = signers[0];
    const mk = () => ethers.Wallet.createRandom().connect(ethers.provider);
    [platform, affiliate, sdg, hotel] = [mk(), mk(), mk(), mk()];
    guests = Array.from({ length: Number(process.env.GUESTS || 5) }, mk);
    const fund = ethers.parseEther(process.env.FUND_ETH || "0.01");
    const bal = await ethers.provider.getBalance(admin.address);
    const need = fund * BigInt(guests.length) + ethers.parseEther("0.03");
    console.log(`admin ${admin.address} balance ${ethers.formatEther(bal)} ETH; needs about ${ethers.formatEther(need)} ETH (unused ETH is returned at the end)`);
    if (bal < need) throw new Error("Saldo ETH Sepolia kurang. Isi dari faucet lalu jalankan ulang.");
    fs.mkdirSync("results", { recursive: true });
    fs.writeFileSync(`results/${LABEL}_ephemeral_wallets.json`, JSON.stringify({ note: "Test-only wallets generated by the campaign; keep private.",
      roles: { platform: platform.address, affiliate: affiliate.address, sdg: sdg.address, hotel: hotel.address },
      guests: guests.map(g => ({ address: g.address, privateKey: g.privateKey })) }, null, 1));
    for (const g of guests) await send("fundGuest", admin, () => admin.sendTransaction({ to: g.address, value: fund }), "");
  }
  console.log(`network ${hre.network.name} chainId ${net.chainId}; guests ${guests.length}; bookings ${N}`);

  let tok, esc;
  if (process.env.ESCROW && process.env.TOKEN) {
    tok = await ethers.getContractAt("MockStablecoin", process.env.TOKEN);
    esc = await ethers.getContractAt("BookingEscrow", process.env.ESCROW);
  } else {
    tok = await (await ethers.getContractFactory("MockStablecoin", admin)).deploy(); await tok.waitForDeployment();
    esc = await (await ethers.getContractFactory("BookingEscrow", admin)).deploy(await tok.getAddress(), platform.address, affiliate.address, sdg.address, 500, 300, 200, MODE);
    await esc.waitForDeployment();
  }
  const deploy = { token: await tok.getAddress(), escrow: await esc.getAddress(),
    tokenDeployTx: tok.deploymentTransaction()?.hash || "", escrowDeployTx: esc.deploymentTransaction()?.hash || "" };
  console.log("deployed", deploy);

  for (const g of guests) {
    await send("mint", admin, () => tok.connect(admin).mint(g.address, 10n ** 12n), "");
    await send("approve", g, () => tok.connect(g).approve(deploy.escrow, ethers.MaxUint256), "");
  }

  // bookings run concurrently in waves (one wave per guest) to create realistic mempool contention
  const lead = Number(process.env.LEAD_S || 90);     // check-in = now + lead
  const stay = Number(process.env.STAY_S || 60);     // check-out = check-in + stay
  const toComplete = [];
  let next = 0;
  async function guestWorker(g) {
    while (next < N) {
      const i = next++;
      const amount = BigInt(Math.round(296 * Math.exp(0.5 * (R() * 2 - 1)) * 1e6));
      const now = (await ethers.provider.getBlock("latest")).timestamp;
      const hash = ethers.keccak256(ethers.toUtf8Bytes(`dry-run-record-${i}`));
      const id = await esc.nextId(); // read before; reconciled from the event below
      const c = await send("createBooking", g, () => esc.connect(g).createBooking(hotel.address, amount, now + lead, now + lead + stay, hash), "");
      if (!c.rc) continue;
      const ev = c.rc.logs.map(l => { try { return esc.interface.parseLog(l); } catch { return null; } }).find(e => e && e.name === "BookingCreated");
      const bid = ev ? ev.args[0] : id; c.row.bookingId = bid.toString();
      await sleep(Number(process.env.WALLET_DELAY_MS || 1500) * (0.5 + R()));   // wallet-approval delay
      const p = await send("confirmPayment", g, () => esc.connect(g).confirmPayment(bid), bid.toString());
      if (!p.rc) continue;
      if (R() < CANCEL_SHARE) {
        await send("cancel", g, () => esc.connect(g).cancel(bid), bid.toString());
        await send("refund", g, () => esc.connect(g).refund(bid), bid.toString());
      } else toComplete.push({ bid, checkOut: now + lead + stay });
    }
  }
  await Promise.all(guests.map(guestWorker));

  // settlement after check-out
  for (const b of toComplete) {
    while ((await ethers.provider.getBlock("latest")).timestamp < b.checkOut) await sleep(3000);
    await send("completeStay", admin, () => esc.connect(admin).completeStay(b.bid), b.bid.toString());
  }
  if (MODE === 1) for (const who of [hotel, platform, affiliate, sdg]) await send("withdraw", who, () => esc.connect(who).withdraw(), "");

  // return unused ETH from generated guest wallets to the admin
  if (ephemeral) {
    const fee = await ethers.provider.getFeeData();
    const maxFee = (fee.maxFeePerGas ?? fee.gasPrice) * 2n, tip = fee.maxPriorityFeePerGas ?? 1n;
    for (const g of guests) {
      try { const b = await ethers.provider.getBalance(g.address); const cost = 21000n * maxFee;
        if (b > cost) await (await g.sendTransaction({ to: admin.address, value: b - cost, gasLimit: 21000n, maxFeePerGas: maxFee, maxPriorityFeePerGas: tip < maxFee ? tip : maxFee })).wait();
      } catch (e) { console.log("sweep skipped for", g.address, (e.shortMessage || e.message).slice(0, 80)); }
    }
  }

  // finality on a sample of guest-facing transactions
  const guestRows = rows.filter(r => ["createBooking", "confirmPayment"].includes(r.function) && r.status === 1);
  const fin = process.env.SKIP_FINALITY ? [] : await finalityLatency(guestRows.slice(0, 5));

  // summary
  const fnNames = [...new Set(rows.map(r => r.function))];
  const byFn = Object.fromEntries(fnNames.map(f => {
    const rs = rows.filter(r => r.function === f); const ok = rs.filter(r => r.status === 1);
    const lat = ok.map(r => Number(r.inclusionLatencyS)); const gas = ok.map(r => Number(r.gasUsed));
    return [f, { n: rs.length, success: ok.length, successRate: ok.length / rs.length, latencyMedianS: q(lat, 0.5), latencyP95S: q(lat, 0.95), gasMedian: q(gas, 0.5) }];
  }));
  const gl = guestRows.map(r => Number(r.inclusionLatencyS));
  const escBal = await tok.balanceOf(deploy.escrow);
  const summary = { label: LABEL, network: hre.network.name, chainId: net.chainId.toString(), mode: MODE ? "accrue" : "push",
    bookings: N, deploy, totalTx: rows.length, failedTx: rows.filter(r => r.status !== 1).length,
    successRate: rows.filter(r => r.status === 1).length / rows.length,
    guestFacing: { n: gl.length, medianS: q(gl, 0.5), p95S: q(gl, 0.95), p99S: q(gl, 0.99) },
    guestFacingBlockBased: { medianS: q(guestRows.map(r => Number(r.blockLatencyS)), 0.5), p95S: q(guestRows.map(r => Number(r.blockLatencyS)), 0.95) },
    finality: { sampled: fin.length, medianS: q(fin, 0.5) }, byFunction: byFn,
    explorer: net.chainId === 11155111n && hre.network.name === "sepolia" ? { escrow: `https://sepolia.etherscan.io/address/${deploy.escrow}`, token: `https://sepolia.etherscan.io/address/${deploy.token}` } : null, escrowResidualAfterRun: escBal.toString() };
  fs.mkdirSync("results", { recursive: true });
  const cols = Object.keys(rows[0]);
  fs.writeFileSync(`results/${LABEL}_tx.csv`, [cols.join(","), ...rows.map(r => cols.map(c => JSON.stringify(r[c] ?? "")).join(","))].join("\n"));
  fs.writeFileSync(`results/${LABEL}_summary.json`, JSON.stringify(summary, null, 1));
  console.log(JSON.stringify(summary, null, 1));
}
main().catch(e => { console.error(e); process.exit(1); });
